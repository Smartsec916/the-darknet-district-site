"""Writes void-runner/vesper-sites-data.js: one key per Vesper road site (village, mine, facility), each written by that site's builder, so a site's model and
its collision boxes, lamps, floors and places always come from the same numbers. update(key, value) keeps the other sites' entries. Made by Claude."""
import json, os, re
REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
DATA_JS = os.path.join(REPO, 'void-runner', 'vesper-sites-data.js')


def load():
    if not os.path.exists(DATA_JS):
        return {}
    m = re.search(r'const DATA=(\{.*\});\n', open(DATA_JS).read(), re.S)
    return json.loads(m.group(1)) if m else {}


def update(key, value):
    data = load()
    data[key] = value
    order = [k for k in ('village', 'mine', 'facility') if k in data] + sorted(k for k in data if k not in ('village', 'mine', 'facility'))
    data = {k: data[k] for k in order}
    with open(DATA_JS, 'w') as f:
        f.write('/* GENERATED by tools/assets/vesper/build_vesper_*.py (do not edit by hand): the Vesper road sites\' collision boxes, lamps, floors and places, in each\n'
                '   site\'s own metres (origin: world x, z; y = the road\'s height there at runtime). vesper-sites.js turns them into world metres. */\n')
        f.write('(function(root){const DATA=' + json.dumps(data, separators=(',', ':')) + ';\n')
        f.write("if(typeof module!=='undefined'&&module.exports)module.exports=DATA;else root.VoidVesperSitesData=DATA;})(globalThis);\n")
