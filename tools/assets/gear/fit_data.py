"""Writes void-runner/assets/models/gear/gear-fit.json: for each of the 11 outfit bodies, the rest-pose joint positions the gear is placed against and the sizes it is scaled by.
Plain Python (no Blender). Run again if a character file changes:   python tools/assets/gear/fit_data.py
The gear parts are authored on two reference bodies (male = district-smuggler, female = district-resident); at load time the game moves and scales each piece from the
reference body's joint to the outfit's own (the way hairstyle parts are refitted), because the outfit files are built on bodies of different sizes."""
import json, os, struct
import numpy as np

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
CROWD = os.path.join(REPO, 'void-runner', 'assets', 'models', 'crowd')
OUT = os.path.join(REPO, 'void-runner', 'assets', 'models', 'gear', 'gear-fit.json')
JOINTS = ['Head', 'Neck', 'Spine2', 'LeftShoulder', 'RightShoulder', 'LeftArm', 'RightArm']


def glb_json(path):
    d = open(path, 'rb').read()
    n = struct.unpack_from('<I', d, 12)[0]
    return json.loads(d[20:20 + n])


def quat(q):
    x, y, z, w = q
    return np.array([[1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)], [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)], [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]])


def world_positions(j):
    nodes, parent, cache = j['nodes'], {}, {}
    for i, n in enumerate(nodes):
        for c in n.get('children', []):
            parent[c] = i

    def W(i):
        if i in cache:
            return cache[i]
        n = nodes[i]
        M = np.eye(4)
        M[:3, :3] = quat(n.get('rotation', [0, 0, 0, 1])) * np.array(n.get('scale', [1, 1, 1]))
        M[:3, 3] = n.get('translation', [0, 0, 0])
        cache[i] = (W(parent[i]) @ M) if i in parent else M
        return cache[i]
    return {n.get('name'): W(i)[:3, 3] for i, n in enumerate(nodes)}


SKIP = ('eye', 'lash', 'brow', 'teeth', 'tongue', 'low-poly', 'short', 'bob', 'braid', 'long', 'ponytail', 'fedora', 'shades', 'visor', 'mask', 'collar', 'shoes', 'hair')


def torso_front(path, j, spine2, span):
    d = open(path, 'rb').read()
    n = struct.unpack_from('<I', d, 12)[0]
    off = 20 + n + 8
    best = -9
    for mesh in j['meshes']:
        if any(k in mesh['name'].lower() for k in SKIP):
            continue
        for prim in mesh['primitives']:
            a = j['accessors'][prim['attributes']['POSITION']]
            bv = j['bufferViews'][a['bufferView']]
            v = np.frombuffer(d, dtype=np.float32, count=a['count'] * 3, offset=off + bv.get('byteOffset', 0) + a.get('byteOffset', 0)).reshape(-1, 3)
            m = (np.abs(v[:, 0] - spine2[0]) < span * .12) & (v[:, 1] > spine2[1] + .02) & (v[:, 1] < spine2[1] + .12)
            if m.any():
                best = max(best, float(v[m][:, 2].max()))
    return round(best, 5)


def main():
    bind = json.load(open(os.path.join(REPO, 'void-runner', 'assets', 'models', 'parts', 'bind-data.json')))['bodies']
    cat = json.load(open(os.path.join(REPO, 'void-runner', 'character-catalog.json')))
    bodies = {}
    for look in cat['looks'].values():
        model = look['model']
        if model in bodies:
            continue
        pos = world_positions(glb_json(os.path.join(CROWD, model + '.glb')))
        joints = {k: [round(float(v), 5) for v in pos['mixamorig:' + k]] for k in JOINTS}
        span = abs(joints['LeftArm'][0] - joints['RightArm'][0])
        jj = glb_json(os.path.join(CROWD, model + '.glb'))
        front = torso_front(os.path.join(CROWD, model + '.glb'), jj, joints['Spine2'], span)
        bodies[model] = {'base': look['base'], 'topY': bind[model]['topY'], 'headW': bind[model]['headDims'][0], 'span': round(span, 5), 'chestFront': front, 'joints': joints}
    out = {'note': 'Generated by tools/assets/gear/fit_data.py. Rest-pose joints and sizes of every outfit body; the gear is moved and scaled from the reference body to each of these.',
           'reference': {'male': 'district-smuggler', 'female': 'district-resident'}, 'bodies': dict(sorted(bodies.items()))}
    with open(OUT, 'w') as f:
        json.dump(out, f, indent=1)
    print('wrote', OUT, len(bodies), 'bodies')


if __name__ == '__main__':
    main()
