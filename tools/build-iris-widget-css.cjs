#!/usr/bin/env node
/* Builds iris-widget.css: the Iris chat window's look on every page except the homepage, from the homepage's own styles.
 *
 * The homepage styles the window in two places: a <style> block in index.html (the base window) and accents.css (the glass
 * capsule button, the phone layout and the large desktop window, all scoped to body.site-home). Rather than copy and
 * hand-edit them (and let the copies drift), this script cuts those rules out and re-scopes them to body.iris-widget-page,
 * the class iris-widget.js puts on the other pages. tests/iris-widget.test.cjs rebuilds the file and fails if the
 * committed one differs, so a change to the homepage's chat styles cannot be forgotten here.
 *
 *   node tools/build-iris-widget-css.cjs          writes iris-widget.css
 *   require('./tools/build-iris-widget-css.cjs').build()   returns the text (used by the test)
 */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');

function between(text, startMarker, endMarker, label) {
  const a = text.indexOf(startMarker);
  if (a < 0) throw new Error(`build-iris-widget-css: cannot find the start of ${label}`);
  const b = endMarker ? text.indexOf(endMarker, a + startMarker.length) : text.length;
  if (b < 0) throw new Error(`build-iris-widget-css: cannot find the end of ${label}`);
  return text.slice(a, b);
}

function build() {
  const index = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  const accents = fs.readFileSync(path.join(root, 'accents.css'), 'utf8');

  // 1. The base window, as the homepage's inline style block has it (from the button up to the first product-card rule)
  const base = between(index, '    .chat-button {', '    .product-card {', 'the base chat styles in index.html')
    .split('\n').map(line => line.replace(/^    /, '')).join('\n').trimEnd();

  // 2. The glass capsule button
  const capsule = between(accents, '/* ---------------------------------------------------------------------------\n   IRIS CAPSULE', '/* ---------------------------------------------------------------------------\n   HUD ON THE HOMEPAGE', 'the Iris capsule in accents.css').trimEnd();

  // 3. hud.css lifts every top-level element into the page flow; the window and the button stay pinned to the screen
  const pinned = between(accents, 'body.site-home[data-hud="immersive"] > #chatButton,', '}', 'the pinned rule in accents.css') + '}';

  // 4. The phone layout, the large desktop window and the reduced-motion rule (the last three blocks of accents.css)
  const windows = between(accents, '/* ---------------------------------------------------------------------------\n   IRIS CHAT WINDOW ON PHONES', null, 'the chat window layouts in accents.css').trimEnd();

  const body = [
    `/* GENERATED by tools/build-iris-widget-css.cjs from the homepage's chat styles (index.html and accents.css); do not edit by hand.`,
    `   The Iris chat window on every page but the homepage. iris-widget.js adds the class iris-widget-page to the body. */`,
    '',
    base,
    '',
    capsule,
    '',
    `/* hud.css lifts every top-level element into the page flow; the window and the button stay pinned to the screen. */`,
    pinned,
    '',
    `@media (prefers-reduced-motion: reduce) {\n  body.site-home .tdd-iris-avatar svg {\n    animation: none !important;\n  }\n}`,
    '',
    windows,
    '',
    `/* The button sits over the bottom right corner of the screen; room under the last line of every page so nothing at the end of a page is hidden behind it. */\nbody.iris-widget-page {\n  padding-bottom: calc(76px + env(safe-area-inset-bottom, 0px));\n}`,
    '',
    `/* style.css keeps the immersive pages from scrolling sideways, but not every page loads it (leaks.html does not): there the page was wider than a phone screen and the fixed button ended up beyond the visible edge. The same rule as style.css (on the root too, which phones need), so nothing changes where it is already applied. */\nhtml.iris-widget-html,\nbody.iris-widget-page[data-hud="immersive"] {\n  max-width: 100%;\n  overflow-x: hidden;\n}`,
    '',
  ].join('\n');

  return body.replace(/body\.site-home/g, 'body.iris-widget-page').replace(/var\(--tdd-pink\)/g, 'var(--tdd-pink, #ff3366)');
}

module.exports = { build };

if (require.main === module) {
  fs.writeFileSync(path.join(root, 'iris-widget.css'), build());
  console.log('wrote iris-widget.css');
}
