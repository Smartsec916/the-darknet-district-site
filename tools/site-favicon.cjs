#!/usr/bin/env node
/* Puts the site's favicon links in the <head> of every top-level page (and its static/ copy), so browsers and Google Search show the Darknet District logo.
   The artwork is the owner's own logo files (favicon-48x48.png, favicon-96x96.png, favicon-192x192.png); favicon.ico and apple-touch-icon.png are scaled copies.
   Idempotent. `node tools/site-favicon.cjs` writes; `--check` only reports pages that are out of date. Line endings of each page are preserved. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),root=path.join(__dirname,'..');
const start='<!-- Site icon: generated by tools/site-favicon.cjs -->',end='<!-- /Site icon -->';
const FILES=['favicon.ico','favicon-48x48.png','favicon-96x96.png','favicon-192x192.png','apple-touch-icon.png'];
const block=[start,
 '<link rel="icon" type="image/png" sizes="48x48" href="/favicon-48x48.png">',
 '<link rel="icon" type="image/png" sizes="96x96" href="/favicon-96x96.png">',
 '<link rel="icon" type="image/png" sizes="192x192" href="/favicon-192x192.png">',
 '<link rel="shortcut icon" href="/favicon.ico">',
 '<link rel="apple-touch-icon" sizes="180x180" href="/apple-touch-icon.png">',
 end].join('\n');
const pages=()=>fs.readdirSync(root).filter(f=>f.endsWith('.html')).sort();
function update(source){
 const eol=source.includes('\r\n')?'\r\n':'\n',markup=block.replace(/\n/g,eol),generated=new RegExp(start+'[\\s\\S]*?'+end);
 if(generated.test(source))return source.replace(generated,markup);
 if(!/<\/head>/i.test(source))return source;
 return source.replace(/<\/head>/i,markup+eol+'</head>');
}
function generate(check=false){
 const stale=[];
 for(const file of pages())for(const prefix of ['','static/']){const p=path.join(root,prefix+file);if(!fs.existsSync(p))continue;const s=fs.readFileSync(p,'utf8'),n=update(s);if(n!==s){stale.push(prefix+file);if(!check)fs.writeFileSync(p,n);}}
 return stale;
}
if(require.main===module){const check=process.argv.includes('--check'),stale=generate(check);if(check&&stale.length){console.error('Stale site icon links:',stale);process.exit(1);}console.log(check?'Site icon links are current.':'Updated '+stale.length+' pages.');}
module.exports={FILES,block,pages,update,generate,start,end};
