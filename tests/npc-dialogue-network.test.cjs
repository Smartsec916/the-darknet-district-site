const {test}=require('node:test');
const assert=require('node:assert/strict');
const {NpcDialogue}=require('../tools/district-hub/npc-dialogue.cjs');
test('a shared turn survives interruption by one listener and the last departure starts cooldown',()=>{
 let now=0;
 const events=[];
 const book=new NpcDialogue(()=>now,(to,event)=>events.push({to,...event}));
 const peer=conn=>({conn,room:'district-interior',placed:true,x:1,z:2});
 const a=peer('one'), b=peer('two'), other={...peer('three'),room:'another'};
 const request={t:'npc-ready',group:'pair',cooldown:5};
 book.handle(a,request);book.handle(b,request);book.handle(other,request);
 now=700;book.handle(b,request);
 assert.deepEqual(events.map(e=>[e.to,e.turn]),[['one',0],['two',0]]);
 const end={t:'npc-end',group:'pair',token:events[0].token};
 book.handle(other,end);book.handle(b,{...end,token:0});book.handle(a,end);
 now=10000;book.handle(a,request);assert.equal(events.length,2);
 book.depart(b);
 now=14999;book.handle(a,request);assert.equal(events.length,2);
 now=15200;book.handle(a,request);assert.equal(events.at(-1).turn,1);
 assert.equal(events.length,3);
});

test('a queued listener cannot receive a second group turn while already listening',()=>{
 let now=0;
 const events=[];
 const book=new NpcDialogue(()=>now,(to,event)=>events.push({to,...event}));
 const peer=conn=>({conn,room:'district-interior',placed:true,x:1,z:2});
 const a=peer('a'),b=peer('b'),c=peer('c');
 const ready=group=>({t:'npc-ready',group,cooldown:5});
 book.handle(a,ready('second'));
 now=200;book.handle(a,ready('first'));book.handle(b,ready('first'));
 now=850;book.handle(b,ready('first'));
 book.handle(c,ready('second'));
 assert.deepEqual(events.map(e=>[e.to,e.group]),[['a','first'],['b','first'],['c','second']]);
 now=1100;book.handle(a,ready('third'));
 assert.equal(book.groups.has('district-interior/third'),false);
});
test('finishing, disconnecting, and expiring a turn release only its listener leases',()=>{
 let now=0;
 const events=[];
 const book=new NpcDialogue(()=>now,(to,event)=>events.push({to,...event}));
 const peer=conn=>({conn,room:'district-interior',placed:true,x:1,z:2});
 const a=peer('a'),b=peer('b');
 const ready=group=>({t:'npc-ready',group,cooldown:5});
 book.handle(a,ready('first'));book.handle(b,ready('first'));
 now=700;book.handle(b,ready('first'));
 const token=events[0].token;
 book.handle(a,{t:'npc-end',group:'first',token});
 now=900;book.handle(a,ready('second'));
 now=1600;book.handle(a,ready('second'));
 assert.equal(events.at(-1).group,'second');
 const secondToken=events.at(-1).token;
 book.handle(a,{t:'npc-end',group:'first',token});
 now=1800;book.handle(a,ready('third'));
 assert.equal(book.groups.has('district-interior/third'),false);
 book.depart(b);
 now=49600;book.sweep();
 now=49800;book.handle(a,ready('third'));book.handle(b,ready('third'));
 now=50500;book.handle(a,ready('third'));
 assert.deepEqual(events.slice(-2).map(e=>[e.to,e.group]),[['a','third'],['b','third']]);
 assert.notEqual(events.at(-1).token,secondToken);
});
test('unplaced and distant queued listeners do not receive a turn',()=>{
 let now=0;
 const events=[];
 const book=new NpcDialogue(()=>now,(to,event)=>events.push({to,...event}));
 const peer=(conn,x,placed=true)=>({conn,room:'district-interior',placed,x,z:2});
 const a=peer('a',0),far=peer('far',30),unplaced=peer('unplaced',0);
 const request={t:'npc-ready',group:'pair',cooldown:5};
 book.handle(a,request);book.handle(far,request);book.handle(unplaced,request);
 unplaced.placed=false;
 now=700;book.handle(a,request);
 assert.deepEqual(events.map(e=>e.to),['a']);
});
