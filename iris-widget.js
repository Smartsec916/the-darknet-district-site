/*
==============================================================================
THE DARKNET DISTRICT — IRIS ON THE REST OF THE SITE (classic script)

One line on a page, <script src="iris-widget.js" defer></script>, puts the same Iris chat the homepage has on that page:
the same capsule button, window, welcome, backend and behavior. This script does not chat; it only
  1. adds the window and the button to the page (the homepage writes the same markup in its own HTML, so nothing happens there),
  2. loads iris-widget.css (the homepage's chat styles, generated by tools/build-iris-widget-css.cjs), and
  3. loads iris-identity.js and iris-chat.js, once each, if the page does not already have them.
All of it is skipped when the page already has a chat button or has opted out (<body data-iris-widget="off">), so a page can never
get two chats. Pages that must not have Iris (the games and their interfaces) simply do not include this script.

The conversation follows the visitor from page to page through iris-chat.js (this tab's sessionStorage).
==============================================================================
*/
(function () {
  'use strict';
  if (window.__irisWidgetLoaded) return;
  window.__irisWidgetLoaded = true;

  var script = document.currentScript;
  var here = script && script.src ? script.src : location.href;
  var asset = function (name) { return new URL(name, here).href; };

  function el(tag, attrs, children) {
    var node = document.createElement(tag);
    Object.keys(attrs || {}).forEach(function (key) {
      if (key === 'text') node.textContent = attrs[key];
      else node.setAttribute(key, attrs[key]);
    });
    (children || []).forEach(function (child) { node.appendChild(child); });
    return node;
  }

  function link(href, text) {
    return el('a', { href: href, target: '_blank', rel: 'noopener noreferrer', text: text });
  }

  function buildWidget() {
    // The same elements, ids and classes as the homepage's chat (index.html), plus the capsule button accents.js makes there
    var avatar = el('span', { 'class': 'tdd-iris-avatar', 'aria-hidden': 'true' });
    avatar.appendChild(el('img', { src: asset('attached_assets/Iris%2001.webp'), alt: '' }));
    var ring = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    ring.setAttribute('viewBox', '0 0 34 34');
    var circle = document.createElementNS('http://www.w3.org/2000/svg', 'circle');
    circle.setAttribute('cx', '17'); circle.setAttribute('cy', '17'); circle.setAttribute('r', '16.5');
    ring.appendChild(circle);
    avatar.appendChild(ring);
    var label = el('span', { text: 'Chat with Iris' });
    var text = el('span', { 'class': 'tdd-iris-text' }, [label, el('small', { text: 'Online' })]);
    var button = el('button', { 'class': 'chat-button tdd-iris', id: 'chatButton', 'aria-controls': 'chatContainer', 'aria-expanded': 'false', type: 'button' }, [avatar, text]);

    var header = el('div', { 'class': 'chat-header' }, [
      el('img', { src: asset('attached_assets/Iris 01.webp'), alt: 'Iris', 'class': 'profile-pic' }),
      el('h3', { 'class': 'chat-title', text: 'Chatting with Iris' }),
      el('button', { 'class': 'chat-minimize', id: 'chatMinimize', type: 'button', 'aria-label': 'Minimize chat', title: 'Minimize (Esc)', text: '–' }),
    ]);
    var messages = el('div', { 'class': 'chat-messages', id: 'chatMessages', role: 'log', 'aria-live': 'polite' });
    var input = el('div', { 'class': 'chat-input' }, [
      el('input', { type: 'text', id: 'messageInput', placeholder: 'Type your message...' }),
      el('button', { id: 'sendButton', text: 'Send' }),
    ]);
    var credits = el('p', { 'class': 'chat-credits' }, [
      document.createTextNode('Weather: '), link('https://www.met.no/en', 'MET Norway'),
      document.createTextNode(' ('), link('https://creativecommons.org/licenses/by/4.0/', 'CC BY 4.0'),
      document.createTextNode(') · Places: '), link('https://www.openstreetmap.org/copyright', '© OpenStreetMap contributors'),
    ]);
    var container = el('div', { 'class': 'chat-container', id: 'chatContainer', style: 'display: none;', role: 'region', 'aria-label': 'Chat with Iris' }, [header, messages, input, credits]);
    return [button, container];
  }

  // The styles first, then the window: the button never shows up bare and then jumps into its capsule shape. If the stylesheet is slow or fails,
  // the chat still appears after a moment (plain, but working) rather than not at all.
  function loadStyles() {
    return new Promise(function (resolve) {
      var existing = document.querySelector('link[data-iris-widget-css]');
      if (existing) { resolve(); return; }
      var done = false;
      var finish = function () { if (!done) { done = true; resolve(); } };
      var css = el('link', { rel: 'stylesheet', href: asset('iris-widget.css'), 'data-iris-widget-css': '' });
      css.onload = finish; css.onerror = finish;
      document.head.appendChild(css);
      setTimeout(finish, 4000);
    });
  }

  // Classic scripts, one after the other: the chat needs the visitor id from iris-identity.js
  function loadScript(name, alreadyThere) {
    return new Promise(function (resolve) {
      if (alreadyThere()) { resolve(); return; }
      var tag = el('script', { src: asset(name) });
      tag.onload = function () { resolve(); };
      tag.onerror = function () { console.warn('Iris: could not load ' + name); resolve(); };
      document.head.appendChild(tag);
    });
  }

  function start() {
    if (document.getElementById('chatButton') || document.body.getAttribute('data-iris-widget') === 'off') return;
    loadStyles().then(function () {
      if (document.getElementById('chatButton')) return;
      document.body.classList.add('iris-widget-page');
      document.documentElement.classList.add('iris-widget-html');
      buildWidget().forEach(function (node) { document.body.appendChild(node); });
      return loadScript('iris-identity.js', function () { return Boolean(window.IrisIdentity); });
    })
      .then(function () { if (window.IrisIdentity) window.IrisIdentity.anonymousPage = true; })
      .then(function () { return loadScript('iris-chat.js', function () { return Boolean(window.__irisChatLoaded); }); });
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start);
  else start();
})();
